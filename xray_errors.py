def _describe_unix(rc: int) -> ExitReason:
    # Явные коды проверяем до диапазона сигналов: 128..192 — эвристика
    # оболочки, и она не должна перехватывать конкретные коды.
    if rc == 2:
        return _reason(
            "Ошибка в конфигурации Xray",
            "Xray не смог разобрать конфигурацию или аргументы запуска (код 2).",
            "Проверьте выбранный конфиг и повторите подключение. "
            "Если конфиг рабочий — приложите лог к issue.",
        )
    if rc == 126:
        return _reason(
            "Нет прав на запуск Xray",
            "Файл Xray найден, но система не разрешила его выполнить (код 126).",
            "Проверьте права на файл и запустите клиент от администратора/root.",
        )
    if rc == 127:
        return _reason(
            "Не найден исполняемый файл Xray",
            "Система не смогла найти или запустить xray (код 127).",
            "Переустановите клиент: возможно, антивирус удалил файл xray.",
        )

    # Python возвращает отрицательный код для сигналов, оболочки — 128+N.
    signal_no: int | None = None
    if rc < 0:
        signal_no = -rc
    elif 128 <= rc <= 192:
        signal_no = rc - 128

    if signal_no is not None:
        name, detail, suggestion = _UNIX_SIGNALS.get(
            signal_no,
            (
                f"сигнал {signal_no}",
                f"Xray был завершен сигналом {signal_no}.",
                "Проверьте системные логи и отправьте лог Xray в issue.",
            ),
        )
        known = signal_no in _UNIX_SIGNALS
        return _reason(
            f"Xray завершен сигналом {name}",
            detail,
            suggestion,
            known=known,
        )

    return _unknown(rc)


def _describe_windows(rc: int) -> ExitReason:
    unsigned = rc & 0xFFFFFFFF
    low = unsigned if unsigned < 0x80000000 else unsigned - 0x100000000

    entry = _WINDOWS_CODES.get(unsigned) or _WINDOWS_CODES.get(low)
    if entry is not None:
        title, detail, suggestion = entry
        return _reason(title, detail, suggestion)

    if 0 <= rc <= 0xFF:
        # Неизвестный обычный код Win32.
        return _unknown(rc, hint="Код не входит в список известных ошибок Windows.")

    hex_code = f"0x{unsigned:08X}"
    return _unknown(
        rc,
        hint=f"Код Windows {hex_code} не входит в список известных ошибок.",
    )


def describe_exit_code(rc: int | None, platform: str | None = None) -> ExitReason:
    """Возвращает понятное человеку объяснение кода завершения Xray."""
    if rc is None:
        return _reason(
            "Xray завершился",
            "Процесс завершился, но код завершения недоступен.",
            "Переподключитесь; если ошибка повторяется — приложите лог к issue.",
            known=False,
        )

    try:
        code = int(rc)
    except (TypeError, ValueError):
        return _unknown(0, hint=f"Некорректный код завершения: {rc!r}.")

    if code == 0:
        return _reason(
            "Xray завершился",
            "Процесс завершился штатно (код 0), хотя соединение не было "
            "остановлено пользователем.",
            "Переподключитесь. Если это повторяется — приложите лог к issue.",
        )

    if platform is None:
        platform = sys.platform
    if platform == "win32":
        return _describe_windows(code)
    return _describe_unix(code)
