"""Человекопонятные причины завершения Xray.

`subprocess` возвращает разные коды в зависимости от ОС:
- Unix: отрицательный код — сигнал, 128+signal — оболочная запись;
- Windows: код процесса (иногда NTSTATUS вида 0xC0000005).

Модуль не зависит от UI и сетевого стека, чтобы его можно было
использовать и в менеджере Xray, и в диагностике.
"""

from __future__ import annotations

import sys
from dataclasses import dataclass


@dataclass(frozen=True)
class ExitReason:
    title: str
    detail: str
    suggestion: str = ""
    known: bool = True

    @property
    def status_message(self) -> str:
        parts = [self.title]
        if self.detail:
            parts.append(self.detail)
        if self.suggestion:
            parts.append(self.suggestion)
        return ". ".join(p.rstrip(".") for p in parts if p) + "."


def _reason(
    title: str,
    detail: str,
    suggestion: str = "",
    *,
    known: bool = True,
) -> ExitReason:
    return ExitReason(
        title=title,
        detail=detail,
        suggestion=suggestion,
        known=known,
    )


def _unknown(code: int, *, hint: str = "") -> ExitReason:
    suffix = f" {hint}" if hint else ""
    return _reason(
        "Xray завершился с неизвестной ошибкой",
        f"Процесс завершился с кодом {code}.{suffix}",
        "Откройте issue и приложите полный лог Xray — по коду причина неизвестна.",
        known=False,
    )


